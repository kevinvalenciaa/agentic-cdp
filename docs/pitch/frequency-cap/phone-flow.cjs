// Drives the Expo web build of apps/device through the frequency-cap flow and screenshots each state.
const { chromium } = require("playwright");
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const p = await ctx.newPage();
  const errs = [];
  p.on("pageerror", e => errs.push(String(e).slice(0, 200)));
  const shot = async (name) => { await p.waitForTimeout(700); await p.screenshot({ path: `shots/${name}.png` }); console.log("shot", name); };
  const text = async () => (await p.innerText("body")).replace(/\s+/g, " ");
  await p.goto("http://localhost:8081/", { waitUntil: "networkidle", timeout: 180000 });
  await p.waitForTimeout(5000);
  console.log("errors:", errs.length ? errs : "none");
  await shot("phone-01-visit1-offer-delivered");
  await p.getByLabel("Dismiss offer").click();
  await p.waitForTimeout(800);
  console.log("home1:", (await text()).slice(0, 300));
  await shot("phone-02-home-after-offer");
  await p.getByLabel("Open Lift SDK debug panel").click();
  await p.waitForTimeout(900);
  console.log("debug1:", (await text()).slice(0, 900));
  await shot("phone-03-debug-visit1-delivered");
  await p.getByLabel("Close sheet").click({ force: true });
  await p.waitForTimeout(600);
  const cards = p.getByRole("button", { name: /\$\d+/ });
  console.log("product cards:", await cards.count());
  await cards.first().click();
  await p.waitForTimeout(1200);
  console.log("product:", (await text()).slice(0, 200));
  await shot("phone-04-product-open");
  await p.getByLabel("Back").click();
  await p.waitForTimeout(2500);
  console.log("home2:", (await text()).slice(0, 300));
  await shot("phone-05-revisit-suppressed");
  await p.getByLabel("Open Lift SDK debug panel").click();
  await p.waitForTimeout(900);
  console.log("debug2:", (await text()).slice(0, 1400));
  await shot("phone-06-debug-suppressed");
  await p.waitForTimeout(7000);
  await shot("phone-07-debug-after-flush");
  await b.close();
})().catch(e => { console.error("FAILED", String(e).slice(0, 400)); process.exit(1); });
